class FlutterRenderer:
    """Emits a self-contained Flutter app for one UISpec.

    Note on `GeneratedApp`: the template above intentionally keeps a minimal
    surface; the runnable entry point is `main()`. Device-backed sessions use
    the bridge contract (render/bridge.py) once the app runs under `flutter run`
    with the loopback server wired — same contract as Compose/SwiftUI.
    """

    host = "flutter"
    profile = FLUTTER

    @staticmethod
    def _dart_safe_json(spec: dict) -> str:
        """Escape `$` for a Dart raw-string-adjacent embedding.

        Dart interpolates `$identifier` inside normal strings. UISpec paths are
        literally `$state.x` / `$row.x`; unescaped they would be consumed as
        interpolation at compile time (the cycle-1 Kotlin defect, Dart edition).
        Inside r'''...''' raw strings no escaping happens, which is why the
        template uses a raw literal AND we still assert round-trip equality in
        tests/test_embedding_roundtrip.py.
        """
        payload = json.dumps(spec, indent=2)
        # Raw triple-quote literal: content must not contain ''' sequence.
        if "'''" in payload:
            raise RenderErrorFlutter(
                "spec contains ''' which cannot ride in a Dart raw literal")
        return payload

    def emit(self, spec: dict) -> dict[str, str]:
        return {
            "generated_app.dart":
                APP_DART.replace("@@SPEC_JSON@@", self._dart_safe_json(spec))
        }

    def open(self, spec: dict):
        return FlutterSession()


class FlutterSession:
    """Device-backed session placeholder.

    Full bridge wiring (loopback HTTP serving the realized tree, matching
    render/bridge.py's contract) lands with the first simulator run; until
    then opening a device-backed Flutter session raises rather than silently
    degrading to simulation -- see session.assert_measurable's philosophy.
    """

    def __init__(self, port: int | None = None):
        from .bridge import DEFAULT_PORTS
        self.host = "flutter"
        self.port = port or DEFAULT_PORTS.get("flutter", 8784)
        raise RenderErrorFlutter(
            "device-backed Flutter sessions need the bridge server wired into "
            "the generated app and `flutter run` on a simulator/emulator; not "
            "yet implemented")

    def __enter__(self):
        raise RenderErrorFlutter("not implemented")


class SimulatedFlutterSession(SimulatedSession):
    """Pipeline-only stand-in. See session.assert_measurable."""

    def __init__(self, spec: dict):
        super().__init__(spec, FLUTTER)


class RenderErrorFlutter(Exception):
    pass


# re-exported alias so callers catching RenderError catch this too
RenderError = RenderErrorFlutter
