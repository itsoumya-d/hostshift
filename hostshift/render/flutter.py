"""Flutter host: UISpec -> a self-contained Flutter/Dart application.

Why Flutter matters to this benchmark: Google's A2UI generative-UI protocol
ships first-party Flutter renderers, so Flutter is where declarative
agent-generated UIs actually land in production. Measuring whether a generated
spec survives the trip into Flutter's widget + Semantics trees is therefore a
production question, not an academic one.

Design mirrors the other native hosts (see compose.py):

- The emitted app embeds the spec and interprets it at runtime; it never
  re-serializes the spec back out.
- A `RenderedTree`-style registry (here: `realized` list) is populated by the
  widgets themselves as they build, so `/tree` reports what Flutter actually
  composed -- a control that failed to build shows up as a parity gap.
- Accessible names come from each widget's Semantics configuration; Flutter
  associates TextField labels from InputDecoration.labelText automatically,
  which the HostProfile records (`derives_name_from_label=True`, like web).

The embedding seam for this host is Dart string literals. The spec rides in a
single-quoted raw-style literal produced by `_dart_safe_json`: Dart does not
interpolate `$` inside normal single-quoted strings without `${...}` syntax,
but `$` IS interpolated in Dart strings -- so dollars are escaped, exactly as
Kotlin required (cycle-1 defect class).
"""

