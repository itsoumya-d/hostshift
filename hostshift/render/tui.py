class TuiRenderer:
    host = "tui"

    def emit(self, spec: dict) -> dict[str, str]:
        return {"app.py": APP_PY.format(spec_json=json.dumps(spec))}

    def open(self, spec: dict):
        try:
            return TuiSession(spec)
        except ImportError as exc:
            raise RenderError("the terminal host needs Textual: pip install textual") from exc


class TuiSession:
    """Device-backed: runs the generated Textual app and reads its live tree.

    Textual drives an async event loop, so the session runs it on a worker
    thread and marshals calls across. That indirection is unfortunate but
    unavoidable if the session API is to stay synchronous and identical to the
    other hosts -- and keeping the API identical is what makes cross-host
    numbers comparable.
    """

    simulated = False
    host = "tui"

    def __init__(self, spec: dict):
        import textual  # noqa: F401,PLC0415
        import asyncio
        import threading
        import copy
        import json

        loc = {}
        exec(APP_PY.format(spec_json=json.dumps(spec)), loc)
        self._app = loc["GeneratedApp"]()

        self._loop = asyncio.new_event_loop()
        self._ready = threading.Event()
        self._pilot = None

        self._thread = threading.Thread(target=self._run_app, daemon=True)
        self._thread.start()
        self._ready.wait()

    def _run_app(self):
        import asyncio
        asyncio.set_event_loop(self._loop)

        async def run():
            async with self._app.run_test() as pilot:
                self._pilot = pilot
                self._stop_event = asyncio.Event()
                self._ready.set()
                await self._stop_event.wait()

        self._loop.run_until_complete(run())

    def _run_coro(self, coro):
        import asyncio
        future = asyncio.run_coroutine_threadsafe(coro, self._loop)
        return future.result()

    def widget_tree(self) -> Widget:
        return self._run_coro(self._get_widget_tree())

    async def _get_widget_tree(self) -> Widget:
        return widget_from_textual(self._app.screen)

    def state(self) -> dict:
        return self._run_coro(self._get_state())

    async def _get_state(self) -> dict:
        import copy
        return copy.deepcopy(self._app.state)

    def ui_facts(self) -> dict:
        return self._run_coro(self._get_ui_facts())

    async def _get_ui_facts(self) -> dict:
        f = {
            "error_visible": False,
            "empty_state_visible": False,
            "enabled": {},
            "field_values": {},
            "options": {},
            "visible_rows": {},
        }
        for w in [self._app.screen] + list(self._app.screen.walk_children()):
            nid = getattr(w, "id", None)
            cls = type(w).__name__

            if cls == "Static" and w.has_class("tone-error"):
                f["error_visible"] = True
            if cls == "Static" and w.has_class("tone-empty"):
                f["empty_state_visible"] = True

            if nid:
                if cls in ("Input", "Select", "Checkbox", "Button"):
                    f["enabled"][nid] = not getattr(w, "disabled", False)

                if cls in ("Input", "Select"):
                    val = getattr(w, "value", None)
                    if cls == "Select" and not isinstance(val, (str, int, float, bool)) and val is not None:
                        val = None
                    f["field_values"][nid] = val

                if cls == "Select":
                    opts = getattr(w, "_options", [])
                    if opts and len(opts) > 0 and isinstance(opts[0], tuple):
                        f["options"][nid] = [o[1] for o in opts if o[1] is not None]

                if cls == "ListView":
                    f["visible_rows"][nid] = len(list(w.children))

        return f

    def actions(self) -> list[dict]:
        return self._run_coro(self._get_actions())

    async def _get_actions(self) -> list[dict]:
        out = []
        for w in list(self._app.screen.walk_children()):
            nid = getattr(w, "id", None)
            if not nid:
                continue
            cls = type(w).__name__
            kind = {
                "Input": "input", "Select": "choice",
                "Checkbox": "boolean", "Button": "action",
            }.get(cls)
            if kind:
                raw_name = getattr(w, "label", None) or getattr(w, "renderable", None)
                name = str(raw_name).strip() or None if raw_name is not None else None
                if kind == "input":
                    name = None

                val = getattr(w, "value", None)
                if cls == "Select" and not isinstance(val, (str, int, float, bool)) and val is not None:
                    val = None

                opts = []
                if cls == "Select":
                    _opts = getattr(w, "_options", [])
                    if _opts and len(_opts) > 0 and isinstance(_opts[0], tuple):
                        opts = [o[1] for o in _opts if o[1] is not None]

                out.append({
                    "id": nid,
                    "kind": kind,
                    "name": name,
                    "enabled": not getattr(w, "disabled", False),
                    "value": val,
                    "options": opts,
                })

            if cls == "ListView":
                for i, child in enumerate(w.children):
                    label_w = next(iter(child.children), None)
                    raw_label = getattr(label_w, "renderable", "") if label_w else ""
                    out.append({
                        "id": f"{nid}#{i}",
                        "kind": "listItem",
                        "name": str(raw_label).strip() or None,
                        "enabled": not getattr(w, "disabled", False),
                        "value": None,
                        "options": [],
                    })
        return out

    def invoke(self, node_id: str, value: object | None = None) -> None:
        self._run_coro(self._invoke(node_id, value))

    async def _invoke(self, node_id: str, value: object | None) -> None:
        if "#" in node_id:
            list_id, _, idx_str = node_id.partition("#")
            idx = int(idx_str)
            try:
                lst = self._app.query_one(f"#{list_id}")
            except Exception:
                return

            items = list(lst.children)
            if 0 <= idx < len(items):
                item = items[idx]
                if not getattr(item, "id", None):
                    item.id = f"{list_id}_item_{idx}"
                await self._pilot.click(f"#{item.id}")
        else:
            try:
                w = self._app.query_one(f"#{node_id}")
            except Exception:
                return

            cls = type(w).__name__
            if cls == "Input":
                if value is not None:
                    w.value = str(value)
            elif cls == "Select":
                if value is not None:
                    w.value = value
            elif cls == "Checkbox":
                if value is not None:
                    w.value = bool(value)
                else:
                    await self._pilot.click(f"#{node_id}")
            elif cls == "Button":
                await self._pilot.click(f"#{node_id}")

    def close(self) -> None:
        if not hasattr(self, "_loop"):
            return
            
        def _stop():
            self._stop_event.set()
            
        try:
            self._loop.call_soon_threadsafe(_stop)
            self._thread.join(timeout=2.0)
        except Exception:
            pass


