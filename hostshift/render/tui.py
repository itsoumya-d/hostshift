def widget_from_textual(node) -> Widget:
    """Lower a live Textual widget hierarchy into the canonical tree.

    Kept here rather than inside the session so it can be unit tested against
    fixtures without spinning up an event loop.
    """
    from .base import TUI as _TUI  # noqa: PLC0415

    cls = type(node).__name__
    kind = {
        "Vertical": "container", "Horizontal": "container", "Screen": "container",
        "Static": "text", "Label": "text", "Input": "input", "Select": "choice",
        "Checkbox": "boolean", "Button": "action", "ListView": "collection",
        "ListItem": "item", "Rule": "separator",
    }.get(cls, "container")

    # A terminal toolkit exposes no accessible-name channel. Whatever text is
    # visible is all an assistive technology could ever get, and for controls
    # rendered without inline text that is nothing.
    name = None
    if kind in ("text", "action", "boolean", "item"):
        raw = getattr(node, "label", None) or getattr(node, "renderable", None)
        name = str(raw).strip() or None if raw is not None else None
    if kind == "input" and not _TUI.derives_name_from_label:
        name = None

    return Widget(
        kind=kind,
        name=name,
        node_id=getattr(node, "id", None),
        focusable=kind in {"input", "choice", "boolean", "action"},
        children=[widget_from_textual(c) for c in getattr(node, "children", [])],
    )
